let currentAlbum = null;
let currentTrack = null;

let currentSingleRelease = null;
let currentSingleTrackIndex = -1;

let singlesAudio = [];

let isSeeking = false;


function getAudioPath(album, track) {
    const number = String(track.number).padStart(2, "0");
    return `audio/${album.slug}/${number}.mp3`;
}


function formatTime(seconds) {
    if (!Number.isFinite(seconds)) {
        return "0:00";
    }

    const minutes = Math.floor(seconds / 60);
    const remainingSeconds = Math.floor(seconds % 60);

    return `${minutes}:${String(remainingSeconds).padStart(2, "0")}`;
}


function updateTrackRows() {
    document.querySelectorAll(".track").forEach((row) => {
        row.classList.remove("active");

        if (!currentAlbum || !currentTrack) {
            return;
        }

        const sameAlbum = row.dataset.album === currentAlbum.slug;
        const sameTrack = Number(row.dataset.track) === currentTrack.number;

        if (sameAlbum && sameTrack) {
            row.classList.add("active");
        }
    });

    document.querySelectorAll(".single-track").forEach((row) => {
        row.classList.remove("active");

        if (!currentSingleRelease || currentSingleTrackIndex < 0) {
            return;
        }

        const sameRelease = row.dataset.release === currentSingleRelease.slug;
        const sameTrack = Number(row.dataset.trackIndex) === currentSingleTrackIndex;

        if (sameRelease && sameTrack) {
            row.classList.add("active");
        }
    });
}


function playTrack(album, track) {
    const sameTrack =
        currentAlbum?.slug === album.slug &&
        currentTrack?.number === track.number;

    if (sameTrack) {
        if (audio.paused) {
            audio.play();
        } else {
            audio.pause();
        }

        return;
    }

    currentAlbum = album;
    currentTrack = track;

    currentSingleRelease = null;
    currentSingleTrackIndex = -1;

    player.hidden = false;

    playerTitle.textContent = track.title;

    playerCurrent.textContent = "0:00";
    playerDuration.textContent = track.duration;
    playerProgress.value = 0;

    const audioPath = getAudioPath(album, track);

    trackDownload.href = audioPath;
    trackDownload.download = `${track.title}.mp3`;

    audio.src = audioPath;
    audio.load();

    audio.play().catch(() => {
        playerTitle.textContent = `${track.title} - файл не найден`;
    });

    updateTrackRows();
}


function playSingleTrack(release, track, trackIndex) {
    const sameTrack =
        !currentAlbum &&
        currentSingleRelease?.slug === release.slug &&
        currentSingleTrackIndex === trackIndex;

    if (sameTrack) {
        if (audio.paused) {
            audio.play();
        } else {
            audio.pause();
        }
        return;
    }

    currentAlbum = null;
    currentTrack = track;
    currentSingleRelease = release;
    currentSingleTrackIndex = trackIndex;

    player.hidden = false;
    playerTitle.textContent = track.title;
    playerCurrent.textContent = "0:00";
    playerDuration.textContent = "0:00";
    playerProgress.value = 0;

    trackDownload.href = track.file;
    trackDownload.download = `${track.title}.mp3`;

    audio.src = track.file;
    audio.load();

    audio.play().catch(() => {
        playerTitle.textContent = `${track.title} - файл не найден`;
    });

    updateTrackRows();
}


function playNextTrack() {
    if (currentSingleRelease) {
        const nextIndex = currentSingleTrackIndex + 1;
        const nextTrack = currentSingleRelease.tracks[nextIndex];

        if (nextTrack) {
            playSingleTrack(currentSingleRelease, nextTrack, nextIndex);
            return;
        }

        playerToggle.textContent = "▶";
        playerProgress.value = 0;
        playerCurrent.textContent = "0:00";
        updateTrackRows();
        return;
    }

    if (!currentAlbum || !currentTrack) {
        return;
    }

    const currentIndex = currentAlbum.tracks.findIndex(
        (track) => track.number === currentTrack.number
    );

    const nextTrack = currentAlbum.tracks[currentIndex + 1];

    if (nextTrack) {
        playTrack(currentAlbum, nextTrack);
        return;
    }

    playerToggle.textContent = "▶";
    playerProgress.value = 0;
    playerCurrent.textContent = "0:00";
    updateTrackRows();
}


function renderAlbumList(selectedSlug) {
    albumList.innerHTML = "";

    siteData.albums.forEach((album) => {
        const link = document.createElement("a");

        link.href = `?album=${encodeURIComponent(album.slug)}`;
        link.style.color = album.accent_color;
        link.dataset.slug = album.slug;
        link.textContent =
            `${album.slug === selectedSlug ? "→ " : ""}${album.title}`;

        link.addEventListener("click", (event) => {
            event.preventDefault();
            selectAlbum(album.slug, true);
        });

        albumList.appendChild(link);
    });
}


function renderAlbum(album) {
    albumInfo.style.color = album.accent_color;
    trackList.style.color = album.accent_color;

    albumTitle.textContent = album.title;
    albumMeta.textContent =
        `${album.release_year} · ${album.release_type}`;

    albumCover.hidden = false;
    albumCover.alt = album.title;

    albumCover.onload = () => {
        albumCover.hidden = false;
    };

    albumCover.onerror = () => {
        albumCover.hidden = true;
    };

    albumCover.src = album.cover;

    albumLinks.innerHTML = "";

    album.links.forEach((item) => {
        const link = document.createElement("a");

        link.href = item.url;
        link.target = "_blank";
        link.rel = "noopener noreferrer";
        link.textContent = item.name;

        albumLinks.appendChild(link);
    });

    albumDownload.href = `downloads/${album.slug}.zip`;
    albumDownload.download = `${album.title}.zip`;

    trackList.innerHTML = "";

    album.tracks.forEach((track) => {
        const row = document.createElement("div");

        row.className = "track";
        row.dataset.album = album.slug;
        row.dataset.track = track.number;

        const name = document.createElement("span");
        name.className = "track-name";
        name.textContent =
            `${String(track.number).padStart(2, "0")} ${track.title}`;

        const duration = document.createElement("span");
        duration.textContent = track.duration;

        row.addEventListener("click", () => {
            playTrack(album, track);
        });

        row.append(name, duration);
        trackList.appendChild(row);
    });

    if (album.materials.length) {
        const materials = document.createElement("div");
        materials.className = "material-links";

        album.materials.forEach((item) => {
            const link = document.createElement("a");

            link.href = item.url;
            link.target = "_blank";
            link.rel = "noopener noreferrer";
            link.textContent = item.title;

            materials.appendChild(link);
        });

        trackList.appendChild(materials);
    }

    updateTrackRows();
}


function selectAlbum(slug, updateUrl = false) {
    const album =
        siteData.albums.find((item) => item.slug === slug) ||
        siteData.albums[0];

    renderAlbumList(album.slug);
    renderAlbum(album);

    if (updateUrl) {
        const url = new URL(window.location.href);

        url.searchParams.set("album", album.slug);

        history.replaceState(null, "", url);
    }
}


function getSingleAudio(single) {
    return singlesAudio.find((release) => release.title === single.title);
}


function renderSingles() {
    singlesList.innerHTML = "";

    siteData.singles.forEach((single) => {
        const item = document.createElement("div");
        item.className = "single-item";

        const row = document.createElement("div");
        row.className = "single";

        const title = document.createElement("button");
        title.className = "single-title";
        title.type = "button";
        title.textContent = single.title;

        const year = document.createElement("span");
        year.textContent = single.release_year;

        const external = document.createElement("a");
        external.className = "single-external";
        external.href = single.url;
        external.target = "_blank";
        external.rel = "noopener noreferrer";
        external.textContent = "↗";
        external.title = "открыть релиз";

        row.append(title, year, external);
        item.appendChild(row);

        const release = getSingleAudio(single);

        if (release && release.tracks.length === 1) {
            title.addEventListener("click", () => {
                playSingleTrack(
                    release,
                    release.tracks[0],
                    0
                );
            });
        } else if (release && release.tracks.length > 1) {
            const trackContainer = document.createElement("div");
            trackContainer.className = "single-tracks";
            trackContainer.hidden = true;

            release.tracks.forEach((track, trackIndex) => {
                const trackRow = document.createElement("button");
                trackRow.className = "single-track";
                trackRow.type = "button";
                trackRow.dataset.release = release.slug;
                trackRow.dataset.trackIndex = trackIndex;
                trackRow.textContent = track.title;

                trackRow.addEventListener("click", () => {
                    playSingleTrack(
                        release,
                        track,
                        trackIndex
                    );
                });

                trackContainer.appendChild(trackRow);
            });

            title.addEventListener("click", () => {
                trackContainer.hidden =
                    !trackContainer.hidden;

                item.classList.toggle(
                    "open",
                    !trackContainer.hidden
                );
            });

            item.appendChild(trackContainer);
        } else {
            title.addEventListener("click", () => {
                window.open(
                    single.url,
                    "_blank",
                    "noopener,noreferrer"
                );
            });
        }

        if (single.materials.length) {
            const materials = document.createElement("div");
            materials.className = "single-materials";

            single.materials.forEach((material) => {
                const link = document.createElement("a");
                link.href = material.url;
                link.target = "_blank";
                link.rel = "noopener noreferrer";
                link.textContent = material.title;
                materials.appendChild(link);
            });

            item.appendChild(materials);
        }

        singlesList.appendChild(item);
    });

    updateTrackRows();
}


async function loadSinglesAudio() {
    try {
        const response = await fetch("singles_audio.json", {cache: "no-store"});

        if (!response.ok) {
            throw new Error(`HTTP ${response.status}`);
        }

        singlesAudio = await response.json();
    } catch (error) {
        console.error("Не удалось загрузить singles_audio.json:", error);
        singlesAudio = [];
    }

    renderSingles();
}


